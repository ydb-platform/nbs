// Force use of older GLIBC symbol versions for compatibility with older systems
// This significantly reduces GLIBC version requirements for better portability
// Static linking libstdc++ eliminates all GLIBCXX dependencies entirely
//
// GLIBC Compatibility Summary:
// - Main dl* functions: GLIBC 2.2.5 (dlopen, dlsym, dlclose, dlerror)
// - pthread functions: GLIBC 2.2.5-2.3.4 (from static libstdc++)
// - Remaining symbols from static libstdc++ may still require GLIBC 2.34+ on newer build systems
// - To achieve maximum compatibility, compile on an older system (e.g., Debian 10/Ubuntu 18.04)
#ifdef __GLIBC__
    #if __GLIBC__ > 2 || (__GLIBC__ == 2 && __GLIBC_MINOR__ >= 34)
        // On newer systems, force use of older symbol versions for backward compatibility
        __asm__(".symver dlopen,dlopen@GLIBC_2.2.5");
        __asm__(".symver dlclose,dlclose@GLIBC_2.2.5");
        __asm__(".symver dlsym,dlsym@GLIBC_2.2.5");
        __asm__(".symver dlerror,dlerror@GLIBC_2.2.5");
        __asm__(".symver pthread_once,pthread_once@GLIBC_2.2.5");
        __asm__(".symver __libc_start_main,__libc_start_main@GLIBC_2.2.5");
    #endif
    // __pthread_key_create appeared in GLIBC 2.3.4
    #if __GLIBC__ > 2 || (__GLIBC__ == 2 && __GLIBC_MINOR__ >= 34)
        __asm__(".symver __pthread_key_create,__pthread_key_create@GLIBC_2.3.4");
    #endif
#endif

