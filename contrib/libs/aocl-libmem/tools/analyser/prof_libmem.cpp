// Remove all tracefs uprobe events created by this process.
// Writes "-:uprobes/<probe_name>" for each tracked probe to
// /sys/kernel/debug/tracing/uprobe_events.
static void cleanup_uprobes()
{
    if (g_probe_names.empty())
        return;

    int fd = open("/sys/kernel/debug/tracing/uprobe_events",
                  O_WRONLY | O_APPEND);
    if (fd < 0)
        return;

    for (const auto &name : g_probe_names) {
        std::string cmd = "-:uprobes/" + name + "\n";
        /* best-effort: ignore write errors (probe may already be gone) */
        if (write(fd, cmd.c_str(), cmd.length()) < 0) {
            /* silence unused-result warning */
        }
    }
    close(fd);
    g_probe_names.clear();
}

// Old-style BPF map definition structure (matches profiler.bpf.c)
struct bpf_map_def {
    unsigned int type;
    unsigned int key_size;
    unsigned int value_size;
    unsigned int max_entries;
    unsigned int map_flags;
};

// BPF syscall wrapper
static inline int bpf_syscall(int cmd, union bpf_attr *attr, unsigned int size) {
    return syscall(__NR_bpf, cmd, attr, size);
}

// perf_event_open syscall wrapper
static inline int perf_event_open(struct perf_event_attr *attr, pid_t pid,
                                 int cpu, int group_fd, unsigned long flags) {
    return syscall(__NR_perf_event_open, attr, pid, cpu, group_fd, flags);
}

// BPF map creation
static int bpf_create_map(enum bpf_map_type map_type, unsigned int key_size,
                         unsigned int value_size, unsigned int max_entries) {
    union bpf_attr attr = {};
    attr.map_type = map_type;
    attr.key_size = key_size;
    attr.value_size = value_size;
    attr.max_entries = max_entries;

    int fd = bpf_syscall(BPF_MAP_CREATE, &attr, sizeof(attr));
    if (fd < 0) {
        std::cerr << "BPF_MAP_CREATE failed: " << strerror(errno) << std::endl;
    }
    return fd;
}

// BPF program loading
static int bpf_load_program(enum bpf_prog_type type, const struct bpf_insn *insns,
                           size_t insns_cnt, const char *license, char *log_buf,
                           size_t log_buf_size) {
    union bpf_attr attr = {};
    attr.prog_type = type;
    attr.insns = reinterpret_cast<uint64_t>(insns);
    attr.insn_cnt = insns_cnt;
    attr.license = reinterpret_cast<uint64_t>(license);
    attr.log_buf = reinterpret_cast<uint64_t>(log_buf);
    attr.log_size = log_buf_size;
    attr.log_level = log_buf_size > 0 ? 1 : 0;

    int fd = bpf_syscall(BPF_PROG_LOAD, &attr, sizeof(attr));
    if (fd < 0 && log_buf && log_buf_size > 0) {
        std::cerr << "BPF program load failed:\n" << log_buf << std::endl;
    }
    return fd;
}

// Get number of possible CPUs for per-CPU map handling
static int get_num_cpus() {
    static int num_cpus = 0;
    if (num_cpus > 0) return num_cpus;

    // Read from /sys/devices/system/cpu/possible
    std::ifstream cpus("/sys/devices/system/cpu/possible");
    if (cpus.is_open()) {
        std::string line;
        std::getline(cpus, line);
        // Format: "0-N" or "0,2-N" etc.
        size_t dash = line.find_last_of('-');
        if (dash != std::string::npos) {
            num_cpus = std::atoi(line.substr(dash + 1).c_str()) + 1;
        }
    }

    if (num_cpus == 0) num_cpus = 1;  // Fallback
    return num_cpus;
}

// BPF map lookup (handles per-CPU maps)
static int bpf_map_lookup_elem(int fd, const void *key, void *value) {
    union bpf_attr attr = {};
    attr.map_fd = fd;
    attr.key = reinterpret_cast<uint64_t>(key);
    attr.value = reinterpret_cast<uint64_t>(value);

    return bpf_syscall(BPF_MAP_LOOKUP_ELEM, &attr, sizeof(attr));
}

// BPF map update element
static int bpf_map_update_elem(int fd, const void *key, const void *value, uint64_t flags) {
    union bpf_attr attr = {};
    attr.map_fd = fd;
    attr.key = reinterpret_cast<uint64_t>(key);
    attr.value = reinterpret_cast<uint64_t>(value);
    attr.flags = flags;

    return bpf_syscall(BPF_MAP_UPDATE_ELEM, &attr, sizeof(attr));
}

// BPF per-CPU map lookup - sums values across all CPUs
static uint64_t bpf_map_lookup_elem_percpu_sum(int fd, const void *key) {
    int num_cpus = get_num_cpus();
    std::vector<uint64_t> values(num_cpus, 0);

    if (bpf_map_lookup_elem(fd, key, values.data()) < 0) {
        return 0;
    }

    uint64_t sum = 0;
    for (int i = 0; i < num_cpus; i++) {
        sum += values[i];
    }
    return sum;
}

// Parse alignment value string and return alignment in bytes.
// Accepts numeric values (bytes) or human-readable forms: B, KB, MB, GB.
// Returns 0 on error, sets error_msg.
static uint32_t parse_alignment_value(const std::string& input, std::string& error_msg) {
    std::string s = input;
    // Convert to uppercase
    for (auto& c : s) c = static_cast<char>(toupper(static_cast<unsigned char>(c)));

    // Strip trailing whitespace
    while (!s.empty() && isspace(static_cast<unsigned char>(s.back()))) s.pop_back();
    while (!s.empty() && isspace(static_cast<unsigned char>(s.front()))) s.erase(s.begin());

    uint64_t multiplier = 1;
    if (s.size() >= 2 && s.substr(s.size() - 2) == "GB") {
        multiplier = 1024ULL * 1024 * 1024;
        s = s.substr(0, s.size() - 2);
    } else if (s.size() >= 2 && s.substr(s.size() - 2) == "MB") {
        multiplier = 1024ULL * 1024;
        s = s.substr(0, s.size() - 2);
    } else if (s.size() >= 2 && s.substr(s.size() - 2) == "KB") {
        multiplier = 1024;
        s = s.substr(0, s.size() - 2);
    } else if (s.size() >= 1 && s.back() == 'B') {
        multiplier = 1;
        s = s.substr(0, s.size() - 1);
    }

    // Strip whitespace between number and suffix
    while (!s.empty() && isspace(static_cast<unsigned char>(s.back()))) s.pop_back();

    char* end = nullptr;
    long val = strtol(s.c_str(), &end, 10);
    if (end == s.c_str() || *end != '\0' || val <= 0) {
        error_msg = "Invalid alignment value: '" + input + "'. "
                    "Expected a number optionally followed by B, KB, MB, or GB.";
        return 0;
    }

    uint64_t alignment_bytes = static_cast<uint64_t>(val) * multiplier;

    // Check power of two
    if ((alignment_bytes & (alignment_bytes - 1)) != 0) {
        error_msg = "Alignment must be a power of two, got " + std::to_string(alignment_bytes) + " bytes.";
        return 0;
    }

    // Must fit in uint32_t for BPF map (mask = alignment - 1)
    if (alignment_bytes > 0x80000000ULL) {
        error_msg = "Alignment too large (max 2GB for BPF mask).";
        return 0;
    }

    return static_cast<uint32_t>(alignment_bytes);
}

// Return a human-readable label for alignment in bytes (e.g., "64B", "4KB").
static std::string format_alignment_label(uint32_t alignment_bytes) {
    if (alignment_bytes >= 1024 * 1024 * 1024 && alignment_bytes % (1024 * 1024 * 1024) == 0)
        return std::to_string(alignment_bytes / (1024 * 1024 * 1024)) + "GB";
    if (alignment_bytes >= 1024 * 1024 && alignment_bytes % (1024 * 1024) == 0)
        return std::to_string(alignment_bytes / (1024 * 1024)) + "MB";
    if (alignment_bytes >= 1024 && alignment_bytes % 1024 == 0)
        return std::to_string(alignment_bytes / 1024) + "KB";
    return std::to_string(alignment_bytes) + "B";
}

