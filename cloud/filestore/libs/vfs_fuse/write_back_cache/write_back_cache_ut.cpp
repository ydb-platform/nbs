    void TestShouldReadAfterWriteRandomized(const TTestArgs& args) {
        TBootstrap b({
            .ZeroCopyWriteEnabled = args.ZeroCopyWriteEnabled,
            .DoNotCheckWriteDataRequestBuffer =
                !args.FlushWritesInParallelEnabled,
            .FlushWritesInParallelEnabled = args.FlushWritesInParallelEnabled,
        });

        const TString alphabet = "abcdefghijklmnopqrstuvwxyz";

        int flushesRemaining = 10;
        int writesRemaining = 333;

        TStatsCalculator stats;

        while (writesRemaining--) {
            const ui64 offset = RandomNumber(alphabet.length());
            const ui64 length = Max(
                1ul,
                RandomNumber(alphabet.length() - offset));

            auto data = TStringBuf(alphabet).SubString(offset, length);

            ui32 nodeId = RandomNumber(3u);

            if (args.ZeroCopyWriteEnabled && RandomNumber(2u) == 0) {
                TIovecs iovecs;
                while (!data.empty()) {
                    const ui64 chunkSize = RandomNumber(data.size()) + 1;
                    iovecs.emplace_back(data.data(), chunkSize);
                    data.remove_prefix(chunkSize);
                }
                b.WriteToCacheSync(nodeId, offset + RandomNumber(11u), iovecs);
            } else {
                b.WriteToCacheSync(
                    nodeId,
                    offset + RandomNumber(11u),
                    TString(data));
            }

            stats.Write(nodeId);

            if (RandomNumber(10u) == 0 && flushesRemaining > 0) {
                if (auto nodeId = RandomNumber(4u)) {
                    if (nodeId == 3) {
                        b.FlushCache();
                        stats.FlushAll();
                    } else {
                        b.FlushCache(nodeId);
                        stats.Flush(nodeId);
                    }
                }
                flushesRemaining--;
            }

            if (args.WithCacheRecreation && RandomNumber(20u) == 0) {
                b.RecreateCache();
                // Stats are reset on cache recreation
                stats.FlushCount = 0;
            }

            b.ValidateCache();

            UNIT_ASSERT_VALUES_EQUAL(0, b.Metrics.PendingQueue.Count->Get());

            if (args.FlushWritesInParallelEnabled) {
                UNIT_ASSERT_VALUES_EQUAL(
                    stats.GetUnflushedQueueRequestCount(),
                    b.Metrics.UnflushedQueue.Count->Get());
            } else {
                // If parallel writes are disabled, flush may be triggered in
                // background because of completed flush batches so there can
                // be less unflushed requests than expected
                UNIT_ASSERT_LE(
                    static_cast<ui64>(b.Metrics.UnflushedQueue.Count->Get()),
                    stats.GetUnflushedQueueRequestCount());
            }

            UNIT_ASSERT_VALUES_EQUAL(
                stats.GetNodeCount(),
                b.Metrics.Nodes.Count->Get());

            if (args.FlushWritesInParallelEnabled) {
                // If parallel writes are disabled, multiple Flush operations
                // will be needed to flush all unflushed data - these values
                // will be different
                UNIT_ASSERT_VALUES_EQUAL(
                    stats.FlushCount,
                    b.Metrics.Flush.CompletedCount->Get());
            }
        }

        if (args.WithCacheRecreation) {
            b.RecreateCache();
        }

        b.ValidateCache();

        b.FlushCache();
        b.CheckStatsAreEmpty();
    }

